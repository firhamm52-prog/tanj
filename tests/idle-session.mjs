import assert from 'node:assert/strict';
import {startIdleSession,IDLE_LIMIT} from '../web/idle-session.js';
let time=10000000,user={id:'test'},loggedOut=0,interval;
const values=new Map(),events=new Map();
globalThis.localStorage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)};
globalThis.window={addEventListener:(e,f)=>events.set(e,f),removeEventListener:()=>{}};
globalThis.document={hidden:false,addEventListener:()=>{},body:{append:()=>{}},createElement:()=>({open:false,setAttribute(){},querySelector(){return {};},showModal(){this.open=true;},close(){this.open=false;},remove(){}})};
globalThis.location={replace:()=>{}};
globalThis.setInterval=f=>{interval=f;return 1;};globalThis.clearInterval=()=>{};
const stop=startIdleSession({getUser:()=>user,logout:async()=>{loggedOut++;user=null;},now:()=>time});
assert.equal(Number(values.get('tanj-last-activity-test')),time);
time+=IDLE_LIMIT-120000;await interval();assert.equal(loggedOut,0);
time+=120000;await interval();assert.equal(loggedOut,1);
await interval();assert.equal(loggedOut,1);stop();
user={id:'active'};time+=1000;
startIdleSession({getUser:()=>user,logout:async()=>{loggedOut++;},now:()=>time});
time+=10000;await events.get('pointerdown')();await Promise.resolve();
assert.equal(Number(values.get('tanj-last-activity-active')),time);
time+=IDLE_LIMIT-1;await interval();assert.equal(loggedOut,1);
console.log('PASS: idle deadline, active session renewal, and single logout.');
