CREATE TABLE IF NOT EXISTS orders (
 id TEXT PRIMARY KEY, token TEXT NOT NULL, document TEXT NOT NULL,
 status TEXT NOT NULL, suffix INTEGER NOT NULL, expires INTEGER NOT NULL,
 proof TEXT NOT NULL DEFAULT '', notification TEXT NOT NULL DEFAULT 'none',
 review_note TEXT NOT NULL DEFAULT '', reviewed_by TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS quotes (id TEXT PRIMARY KEY, document TEXT NOT NULL, expires INTEGER NOT NULL);
